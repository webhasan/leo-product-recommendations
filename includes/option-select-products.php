<script>
jQuery(function ($) {
    // Opened from the settings note "Open a product": show the Recommendations tab and point at it.
    var $tab = $('.lpr-product-recommendations_tab');
    if (!$tab.length) return;
    $tab.find('a').trigger('click');

    // Only once: a reload should not replay it.
    try {
        var url = new URL(window.location.href);
        url.searchParams.delete('lpr_tab');
        window.history.replaceState(null, '', url.toString());
    } catch (e) {}

    var box = document.getElementById('woocommerce-product-data');
    if (box) box.scrollIntoView({ block: 'center', behavior: 'smooth' });

    var $tip = $('<div class="lpr-spotlight-tip" role="status"></div>')
        .text(<?php echo wp_json_encode(__('Set this product\'s recommendations here', 'leo-product-recommendations')); ?>);
    var $panel = $('#lpr_product_recommendations_panel');

    setTimeout(function () {
        $tab.addClass('lpr-spotlight').append($tip);
        $panel.addClass('lpr-spotlight-panel');
        requestAnimationFrame(function () { $tip.addClass('is-shown'); });
    }, 450);

    var done = false;
    function end() {
        if (done) return;
        done = true;
        $tip.removeClass('is-shown');
        $tab.removeClass('lpr-spotlight');
        $panel.removeClass('lpr-spotlight-panel');
        setTimeout(function () { $tip.remove(); }, 300);
    }
    setTimeout(end, 6500);
    setTimeout(function () { $(document).one('click keydown', end); }, 600);
});
</script>
<?php endif; ?>